<script>
const csrfToken = $('meta[name="csrf-token"]').attr('content');
let currentReportData = [];
let currentReportTitle = 'Report';

$('#reportForm').on('submit', function (e) {
  e.preventDefault();
  const data = $(this).serialize() + '&action=generate&csrf_token=' + csrfToken;
  $.post(APP_URL + '/api/reports.php', data, function (res) {
    if (!res.success) { toastError(res.message); return; }
    $('#reportResult').show();
    $('#reportTitle').text(res.title + ' (' + res.from + ' to ' + res.to + ')');
    currentReportTitle = res.title || 'Report';
    currentReportData = res.data || [];
    const d = currentReportData;
    if (d.length === 0) { $('#resultTable thead').empty(); $('#resultTable tbody').html('<tr><td class="text-muted py-3">No matching clinical records for this date range.</td></tr>'); return; }
    const headers = Object.keys(d[0]);
    let thead = '<tr>' + headers.map(h => '<th>' + h.replace(/_/g,' ').replace(/\b\w/g, l => l.toUpperCase()) + '</th>').join('') + '</tr>';
    const safeText = value => $('<div>').text(String(value ?? '—')).html();
    let tbody = d.map(row => '<tr>' + headers.map(h => '<td>' + safeText(row[h]) + '</td>').join('') + '</tr>').join('');
    $('#resultTable thead').html(thead);
    $('#resultTable tbody').html(tbody);
  }, 'json').fail(function(){ toastError('Clinical reports are temporarily unavailable. Please retry.'); });
});

// ============================================================
// Export current report as CSV (client-side)
// ============================================================
$('#exportCsvBtn').on('click', function () {
  if (!currentReportData.length) { toastError('Generate a report first.'); return; }
  const rows = currentReportData;
  const headers = Object.keys(rows[0]);
  const esc = v => { const text = String(v ?? ''); return (/^[\s\x00-\x1F]*[=+\-@]/.test(text) ? "'" + text : text).replace(/"/g, '""'); };
  let csv = headers.map(h => '"' + esc(h) + '"').join(',') + '\n';
  rows.forEach(function (r) {
    csv += headers.map(h => '"' + esc(r[h]) + '"').join(',') + '\n';
  });
  const blob = new Blob(['\uFEFF' + csv], { type: 'text/csv;charset=utf-8;' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = currentReportTitle.replace(/[^a-z0-9]+/gi, '_').toLowerCase() + '.csv';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(a.href);
});

$.get(APP_URL + '/api/reports.php', { action: 'history' }, function (res) {
  if (!res.success) return;
  const rows = (res.data || []).map(r => [r.report_type, (r.period_from||'')+' - '+(r.period_to||''), (r.first_name||'')+' '+(r.last_name||''), r.created_at]);
  $('#reportHistory').DataTable({ data: rows, columns:[{},{},{},{}], pageLength: 5, language: { emptyTable: "No reports generated yet." } });
}, 'json');

function printReport() {
  const html = document.getElementById('reportResult').innerHTML;
  const w = window.open('', '', 'width=800,height=600');
  w.document.write('<html><head><title>Report</title><link href="' + APP_URL + '/assets/css/bootstrap.min.css" rel="stylesheet"><link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet"><style>body{font-family:Inter,Arial,sans-serif}</style></head><body><div class="p-4">' + html + '</div></body></html>');
  w.document.close();
  w.print();
}
</script>
