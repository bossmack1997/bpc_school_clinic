<script>
const csrfToken = $('meta[name="csrf-token"]').attr('content');

$('#reportForm').on('submit', function (e) {
  e.preventDefault();
  const data = $(this).serialize() + '&action=generate&csrf_token=' + csrfToken;
  $.post(APP_URL + '/api/reports.php', data, function (res) {
    if (!res.success) { toastError(res.message); return; }
    $('#reportResult').show();
    $('#reportTitle').text(res.title + ' (' + res.from + ' to ' + res.to + ')');
    const d = res.data;
    if (d.length === 0) { $('#resultTable').find('thead, tbody').empty(); return; }
    const headers = Object.keys(d[0]);
    let thead = '<tr>' + headers.map(h => '<th>' + h.replace(/_/g,' ').replace(/\b\w/g, l => l.toUpperCase()) + '</th>').join('') + '</tr>';
    let tbody = d.map(row => '<tr>' + headers.map(h => '<td>' + (row[h] ?? '—') + '</td>').join('') + '</tr>').join('');
    $('#resultTable thead').html(thead);
    $('#resultTable tbody').html(tbody);
  }, 'json');
});

$.get(APP_URL + '/api/reports.php', { action: 'history' }, function (res) {
  if (!res.success) return;
  const rows = res.data.map(r => [r.report_type, (r.period_from||'')+' - '+(r.period_to||''), (r.first_name||'')+' '+(r.last_name||''), r.created_at]);
  $('#reportHistory').DataTable({ data: rows, columns:[{},{},{},{}], pageLength: 5 });
}, 'json');

function printReport() {
  const html = document.getElementById('reportResult').innerHTML;
  const w = window.open('', '', 'width=800,height=600');
  w.document.write('<html><head><title>Report</title><link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/css/bootstrap.min.css"></head><body><div class="p-4">' + html + '</div></body></html>');
  w.document.close();
  w.print();
}
