CREATE TABLE IF NOT EXISTS mica_scans (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, started_at DATETIME NOT NULL, completed_at DATETIME NULL,
 status VARCHAR(20) NOT NULL, duration_ms INT NULL, result_json LONGTEXT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS mica_alert_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, action_id INT NOT NULL, event_type VARCHAR(40) NOT NULL,
 details TEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX mica_event_action (action_id, id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS mica_alert_reads (
 action_id INT NOT NULL, user_id INT NOT NULL, read_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (action_id, user_id)
) ENGINE=InnoDB;
